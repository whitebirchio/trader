/**
 * Regenerate src/agent/earnings-universe.ts (#105): every company with a
 * release scored in the earnings-reaction backtest (it passed risk's
 * price/liquidity filters at entry at least once, 2018–2026), in a fixed
 * order by the SHA-256 of the ticker. The earnings-backfill job fetches them
 * in that order, so whatever is stored at any point is a random sample of
 * the whole list. Reads the git-ignored .cache/earnings-outcomes.json that
 * research:earnings writes; no network.
 *
 *   npm run research:earnings-universe -w @trader/core
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { CACHE, log } from "./research-common.js";

const outcomes = JSON.parse(readFileSync(join(CACHE, "earnings-outcomes.json"), "utf8")) as { event: { ticker: string } }[];
const hash = (t: string) => createHash("sha256").update(t).digest("hex");
const tickers = [...new Set(outcomes.map((o) => o.event.ticker))].sort((a, b) => hash(a).localeCompare(hash(b)));

const lines: string[] = [];
for (let i = 0; i < tickers.length; i += 16) lines.push(`  ${tickers.slice(i, i + 16).join(" ")}`);
const file = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "agent", "earnings-universe.ts");
writeFileSync(
  file,
  `/**
 * The companies the earnings-backfill job fetches (#105), in its order:
 * every company with a release scored in the earnings-reaction backtest
 * (docs/research/earnings-reactions-vs-vti-2026-11.md), ordered by the
 * SHA-256 of the ticker so any prefix is a random sample. Tickers are in
 * Alpaca's form (BRK.B). Generated by \`npm run research:earnings-universe\`;
 * don't edit by hand.
 */
export const EARNINGS_UNIVERSE: readonly string[] = \`
${lines.join("\n")}
\`
  .trim()
  .split(/\\s+/);
`,
);
log(`wrote ${tickers.length} tickers to ${file}`);
